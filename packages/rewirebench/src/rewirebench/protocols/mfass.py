"""Immutable MFASS v2 protocol, with assay-oriented input pairs and held-out scoring.

The cohort is supplied locally because upstream reuse terms are not declared.
Only the canonical split (generated by rewire) is distributed with this package.
"""
from __future__ import annotations

import csv
import hashlib
import io
from importlib.resources import files
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler

from rewirebench.metrics import point_metrics

REVISION = "bee9133b83f3aedaf2bbb9013f1875515845607e"
COHORT_SHA256 = "389702ff4c647d7ce10a90092a6fa811ae777d15997baf39ce9aae0346247bd0"
SPLIT_SHA256 = "999ebcb7e63a5c5eaa8780fa468e59ac1f934260ad50102814174c396317f052"
# 'label' in the upstream file is the variant's anatomical region, not its outcome.
INPUT_FIELDS = (
    "reference_sequence", "mutant_sequence", "rel_position", "rel_position_scaled",
    "intron1_len", "exon_len", "intron2_len", "ref_allele", "alt_allele",
    "strand", "phylop_score", "mean_phastCons_score",
)


def _hash(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def validate_pair(row):
    """Reject the legacy orientation error before model-facing inputs are built."""
    pos = int(row["rel_position"]) - 1
    ref, alt, legacy = (row[k].upper() for k in
                        ("reference_sequence", "mutant_sequence", "sequence"))
    if not (len(ref) == len(alt) == len(legacy) == 170 and 0 <= pos < 170):
        raise ValueError(f"{row['id']}: invalid assay pair length/position")
    if set(ref + alt) - set("ACGT"):
        raise ValueError(f"{row['id']}: unexpected assay bases")
    if [i for i, (a, b) in enumerate(zip(ref, alt)) if a != b] != [pos]:
        raise ValueError(f"{row['id']}: mutation must occur at rel_position - 1")
    complement = str.maketrans("ACGT", "TGCA")
    a, b = row["ref_allele"].upper(), row["alt_allele"].upper()
    if row["strand"] == "-":
        a, b = a.translate(complement), b.translate(complement)
    elif row["strand"] != "+":
        raise ValueError(f"{row['id']}: invalid strand")
    if (ref[pos], alt[pos]) != (a, b):
        raise ValueError(f"{row['id']}: assay alleles differ from the source variant")
    orientation = ("assay" if legacy == alt else "reverse_complement"
                   if legacy == alt.translate(complement)[::-1] else None)
    if orientation is None or orientation != row["legacy_sequence_orientation"]:
        raise ValueError(f"{row['id']}: legacy orientation does not reconcile")


RAW_SHA256 = "a637ca0e307e66ff48811ec7efa22b9ce453bc7883b04f0cacb867f7283132d8"
ANNOTATION_SHA256 = "71a857fe647c4e68acbb41ca61e959c47e1176de89b1442bd6ca1772aa60d5a1"
UPSTREAM_REVISION = "9a8e4f27106be52aeb11acad27f95f5cded663a8"


def _build_cohort(directory):
    """Transcribe reviewed build_dataset.py, preserving its exact CRLF serializer.

    Source tables must already be local. No data or licence acceptance is fetched
    implicitly, and source directories are never modified by preparation.
    """
    tables = []
    for name, expected in (("snv_data_clean.txt", RAW_SHA256),
                           ("snv_func_annot.txt", ANNOTATION_SHA256)):
        path = directory / name
        if _hash(path) != expected:
            raise ValueError(f"Pinned source checksum mismatch: {name}")
        with path.open(newline="") as stream:
            tables.append(list(csv.DictReader(stream, delimiter="\t")))
    raw, annotations = tables
    annot_fields = ["ensembl_gene_id", "symbol", "phylop_score", "mean_phastCons_score", "cadd_score"]
    annotation = {row["id"]: {key: row.get(key, "NA") for key in annot_fields}
                  for row in annotations}
    keep = ["id", "ensembl_id", "chr", "strand", "intron1_len", "exon_len", "intron2_len",
            "start_hg38_0based", "end_hg38_0based", "snp_position_hg38_1based",
            "ref_allele", "alt_allele", "rel_position", "rel_position_scaled", "label", "category",
            "strong_lof", "delta_dpsi", "sequence"]
    records = []
    for row in raw:
        if row["category"] != "mutant" or row["strong_lof"] == "NA":
            continue
        record = {key: row[key] for key in keep}
        record["reference_sequence"] = row["natural_seq"].upper()
        record["mutant_sequence"] = row["original_seq"].upper()
        complement = str.maketrans("ACGT", "TGCA")
        mutant, legacy = record["mutant_sequence"], row["sequence"].upper()
        record["legacy_sequence_orientation"] = (
            "assay" if legacy == mutant else "reverse_complement"
            if legacy == mutant.translate(complement)[::-1] else "invalid")
        validate_pair(record)
        record["sdv"] = 1 if row["strong_lof"] == "TRUE" else 0
        record.update(annotation.get(row["id"], {key: "NA" for key in annot_fields}))
        records.append(record)
    if not records:
        raise ValueError("Empty source cohort")
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(stream, fieldnames=list(records[0]), delimiter="\t")
    writer.writeheader()
    writer.writerows(records)
    return stream.getvalue().encode("utf-8")


def prepare(source: Path, **options):
    source = Path(source)
    cohort = source / "cohort.tsv" if source.is_dir() else source
    split = Path(options.get("split") or cohort.parent / "split-v2.tsv")
    if options.get("split") and not split.exists():
        raise FileNotFoundError(f"Explicit split file does not exist: {split}")
    split_data = (split.read_bytes() if split.exists() else
                  files("rewirebench").joinpath("resources/mfass/split-v2.tsv").read_bytes())
    if hashlib.sha256(split_data).hexdigest() != SPLIT_SHA256:
        raise ValueError("MFASS v2 requires the canonical split-v2.tsv SHA-256")
    cohort_data = cohort.read_bytes() if cohort.exists() else _build_cohort(cohort.parent)
    if hashlib.sha256(cohort_data).hexdigest() != COHORT_SHA256:
        raise ValueError("MFASS v2 requires the pinned validated cohort SHA-256; rebuild from the reviewed revision")
    raw = list(csv.DictReader(io.StringIO(cohort_data.decode("utf-8")), delimiter="\t"))
    split_rows = list(csv.DictReader(split_data.decode().splitlines(), delimiter="\t"))
    sp = {r["id"]: r for r in split_rows}
    ids = [r["id"] for r in raw]
    if len(ids) != 27733 or len(ids) != len(set(ids)) or set(ids) != set(sp):
        raise ValueError("Canonical cohort/split identities do not reconcile")
    rows = []
    for row in raw:
        validate_pair(row)
        inputs = {key: row[key] for key in INPUT_FIELDS}
        inputs["region"] = row["label"]
        rows.append({"id": row["id"], "split": sp[row["id"]]["split"],
                     "inputs": inputs, "target": int(row["sdv"]),
                     "group": sp[row["id"]]["group"]})
    for part, count, positives in (("train", 19409, 735), ("test", 8324, 315)):
        selected = [r for r in rows if r["split"] == part]
        if len(selected) != count or sum(r["target"] for r in selected) != positives:
            raise ValueError("Canonical split counts changed")
    limit = options.get("limit")
    if limit is not None and (isinstance(limit, bool) or int(limit) != limit or limit < 1):
        raise ValueError("limit must be a positive integer")
    scope = "full"
    if limit:
        # Deterministic source order, without selecting on outcomes.
        rows = ([r for r in rows if r["split"] == "train"][:limit] +
                [r for r in rows if r["split"] == "test"][:limit])
        scope = "smoke"
    frozen = options.get("frozen_encoder") or options.get("protocol_id") == "mfass-v2-frozen-encoder"
    return {
        "protocol_id": "mfass-v2-frozen-encoder" if frozen else "mfass-v2",
        "protocol_version": REVISION, "dataset_id": "mfass-assay-pairs-v2",
        "scope": scope, "rows": rows,
        "provenance": {"cohort_sha256": COHORT_SHA256, "split_sha256": SPLIT_SHA256,
                       "runner_revision": REVISION, "upstream_revision": UPSTREAM_REVISION,
                       "raw_sha256": RAW_SHA256, "annotation_sha256": ANNOTATION_SHA256,
                       "source_url": f"https://github.com/rewire-bio/rewire-benchmarks/tree/{REVISION}/benchmarks/mfass"},
        "metadata": {"canonical_train_count": 19409, "canonical_test_count": 8324,
                     "capacity": 100, "input_context": "170bp assay-oriented pair",
                     "source_reuse_terms": "unreported; source data not redistributed",
                     "head": {"C": 0.1, "class_weight": "balanced", "solver": "liblinear",
                              "max_iter": 1000, "seed": 20260914},
                     "smoke_limit_per_split": limit},
    }


def score(dataset, predictions):
    rows = [r for r in dataset["rows"] if r["split"] == "test"]
    all_ids = {r["id"] for r in dataset["rows"]}
    if set(predictions) - all_ids:
        raise ValueError("Unknown prediction IDs")
    selected = [r for r in rows if r["id"] in predictions]
    values = np.asarray([predictions[r["id"]] for r in selected], dtype=float)
    if not np.isfinite(values).all():
        raise ValueError("Nonfinite prediction scores")
    labels = np.asarray([r["target"] for r in selected], dtype=int)
    if len(selected) and len(set(labels)) == 2:
        metrics = point_metrics(labels, values, 100)
    else:
        metrics = {"n": len(selected), "positives": int(labels.sum()), "capacity": 100,
                   "auroc": None, "average_precision_sklearn": None,
                   "precision_at_capacity": None, "recall_at_capacity": None,
                   "unavailable_reason": "No scored rows or only one outcome class"}
    # Keep the canonical denominator even for a deliberately limited smoke run.
    denominator = dataset["metadata"].get("canonical_test_count", len(rows))
    return {"metrics": metrics,
            "coverage": {"scored": len(selected), "unscored": denominator - len(selected),
                         "denominator": denominator, "selected": len(rows)},
            "protocol_id": dataset["protocol_id"], "scope": dataset["scope"],
            "complete": dataset["scope"] == "full" and len(selected) == denominator,
            "score_direction": "higher means more splice disruption",
            "metrics_scope": "scored held-out variants only",
            "unscored_reasons": {"not_selected": denominator - len(rows),
                                 "missing_prediction": len(rows) - len(selected)}}


def fit_embeddings(dataset, embeddings):
    """Fit scaler and fixed logistic head on training rows, never test labels."""
    rows = dataset["rows"]
    if set(embeddings) != {r["id"] for r in rows}:
        raise ValueError("Frozen-pair fitting requires one embedding for every selected row")
    vectors = []
    for row in rows:
        pair = embeddings[row["id"]]
        ref, mut = (np.asarray(pair[key], dtype=np.float32) for key in ("reference", "mutant"))
        if ref.ndim != 1 or ref.size == 0 or ref.shape != mut.shape:
            raise ValueError("Reference and mutant embeddings must be equal nonempty vectors")
        if not np.isfinite(ref).all() or not np.isfinite(mut).all():
            raise ValueError("Nonfinite embeddings")
        vectors.append(np.concatenate((ref, mut - ref)))
    if len({x.shape for x in vectors}) != 1:
        raise ValueError("Embedding dimensions differ across variants")
    vectors = np.asarray(vectors, dtype=np.float32)
    train = np.asarray([r["split"] == "train" for r in rows])
    test = np.asarray([r["split"] == "test" for r in rows])
    ytrain = np.asarray([r["target"] for r in rows if r["split"] == "train"])
    if not train.any() or not test.any() or len(set(ytrain)) != 2:
        raise ValueError("Frozen-pair fitting needs both training classes and held-out rows; increase the smoke limit")
    if dataset["scope"] == "full" and (int(train.sum()) != 19409 or int(test.sum()) != 8324):
        raise ValueError("Full evaluation must retain canonical train/test counts")
    scaler = StandardScaler().fit(vectors[train])
    head = LogisticRegression(C=0.1, class_weight="balanced", solver="liblinear",
                              max_iter=1000, random_state=20260914)
    head.fit(scaler.transform(vectors[train]), ytrain)
    values = head.predict_proba(scaler.transform(vectors[test]))[:, 1]
    return {r["id"]: float(value) for r, value in
            zip([r for r in rows if r["split"] == "test"], values)}
