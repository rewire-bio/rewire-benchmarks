"""Export locked dependencies, substituting the verified Linux CPython 3.11 CPU wheel.

No native uv.lock change and no model-weight download. --verify-upstream reads
only the official index and wheel ZIP metadata through bounded HTTP ranges.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import re
import subprocess
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
URL = "https://download.pytorch.org/whl/cpu/torch-2.2.2%2Bcpu-cp311-cp311-linux_x86_64.whl"
SHA256 = "90089cae572672fb449c8ff1dc1b29daaffa117bf97ede7463dcd2fd1b991e4c"
METADATA_SHA256 = "a9aa8209f788d630c6415e7fbdc0e8e94327ea2ac6e7f16b374f1da9e6e35a6e"
SIZE = 186779302
CPU_DEPENDENCIES = {"filelock", "typing-extensions", "sympy", "networkx", "jinja2", "fsspec"}


class RemoteWheel(io.RawIOBase):
    def __init__(self):
        self.position = 0
        self.downloaded = 0

    def seek(self, offset, whence=0):
        self.position = offset if whence == 0 else self.position + offset if whence == 1 else SIZE + offset
        return self.position

    def tell(self):
        return self.position

    def read(self, size=-1):
        size = SIZE - self.position if size < 0 else size
        if size > 2 * 1024 * 1024:
            raise ValueError("Refusing a range larger than 2 MiB")
        if size == 0:
            return b""
        start, end = self.position, min(SIZE - 1, self.position + size - 1)
        request = urllib.request.Request(
            URL + f"?metadata_range={start}", headers={"Range": f"bytes={start}-{end}"})
        with urllib.request.urlopen(request, timeout=30) as response:
            if response.status != 206 or response.headers.get("Content-Range") != f"bytes {start}-{end}/{SIZE}":
                raise ValueError("Server did not honour the bounded metadata range")
            data = response.read(size + 1)
            if len(data) != end - start + 1:
                raise ValueError("Unexpected range length")
        self.position += len(data)
        self.downloaded += len(data)
        return data


def verify():
    with urllib.request.urlopen("https://download.pytorch.org/whl/cpu/torch/", timeout=30) as response:
        index = response.read().decode()
    if not re.search(r'torch-2\.2\.2(?:%2B|\+)cpu-cp311-cp311-linux_x86_64\.whl#sha256=' + SHA256, index):
        raise ValueError("Official CPU index no longer matches the pinned wheel SHA-256")
    remote = RemoteWheel()
    with zipfile.ZipFile(remote) as wheel:
        metadata = wheel.read("torch-2.2.2+cpu.dist-info/METADATA")
    if hashlib.sha256(metadata).hexdigest() != METADATA_SHA256:
        raise ValueError("Wheel metadata changed")
    dependencies = {line.split(": ", 1)[1].split()[0].lower()
                    for line in metadata.decode().splitlines()
                    if line.startswith("Requires-Dist:") and "extra ==" not in line}
    if dependencies != CPU_DEPENDENCIES:
        raise ValueError(f"Unexpected CPU wheel dependencies: {dependencies}")
    print(f"Verified official index and wheel metadata ({remote.downloaded} bytes; no full wheel download)")


def generate(environment):
    command = ["uv", "export", "--locked", "--no-dev", "--package", "rewirebench", "--extra", environment,
               "--no-emit-workspace", "--format", "requirements-txt"]
    exported = subprocess.check_output(command, cwd=ROOT, text=True)
    if environment == "sequence":
        if any(name in exported for name in ("torch==", "nvidia-", "triton==")):
            raise ValueError("Sequence environment must not acquire model framework dependencies")
        (ROOT / "containers" / "sequence.lock.txt").write_text(exported)
        return
    blocks = re.split(r"(?m)(?=^[A-Za-z0-9][A-Za-z0-9_.-]*(?:==| @ ))", exported)[1:]
    output, names = [], set()
    for block in blocks:
        name = re.match(r"[A-Za-z0-9_.-]+", block).group().lower()
        if name.startswith("nvidia-") or name == "triton":
            continue
        if name == "torch" and not block.startswith("torch==2.2.2 "):
            raise ValueError("Root torch pin changed; review the CPU replacement before regenerating")
        names.add(name)
        output.append(f"torch @ {URL} \\\n    --hash=sha256:{SHA256}\n" if name == "torch" else block)
    if not CPU_DEPENDENCIES.issubset(names) or "numpy==1.26.4" not in "".join(output):
        raise ValueError("Root lock no longer provides the reviewed CPU dependencies/NumPy pin")
    header = ("# Generated by python containers/generate_cpu_locks.py\n"
              "# Linux x86-64 / CPython 3.11 only. Root uv.lock remains unchanged.\n"
              "# Torch CPU wheel and dependency metadata verified in CPU-LOCKS.md.\n")
    (ROOT / "containers" / f"{environment}.lock.txt").write_text(header + "".join(output))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify-upstream", action="store_true")
    args = parser.parse_args()
    if args.verify_upstream:
        verify()
    for environment in ("esm", "dnabert2", "sequence"):
        generate(environment)
